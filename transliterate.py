SUFFIX_TABLES = {"ja": SUFFIX_JA, "ko": SUFFIX_KO, "hi": SUFFIX_HI, "th": SUFFIX_TH}

def pinyin_to_script(syllable, lang):
    """單一拼音音節 -> 目標文字（ja: 片假名, ko: 諺文, hi: 天城文, th: 泰文）。"""
    table = SYLLABLE_TABLES.get(lang)
    return table.get(syllable, syllable) if table else syllable


def localize_word(word, lang):
    """羅馬化詞（拼音或英文後綴）-> 目標語言文字。

    - 拉丁語系：原樣回傳。
    - ja/ko/hi/th：先查後綴字典（英文後綴 -> 目標語），查無則把拼音音節轉成目標文字。
    """
    if lang in LATIN:
        return word
    table = SUFFIX_TABLES.get(lang)
    if table is None:
        return word
    if word in table:
        return table[word]
    if word.isalpha() and word.islower():
        return pinyin_to_script(word, lang)
    return word


def transliterate_syllables(syllables, lang):
    """拼音音節清單 -> 目標文字（拉丁語系回英文標題形式）。"""
    if lang in LATIN:
        return "".join(syllables).capitalize()
    return "".join(pinyin_to_script(s, lang) for s in syllables)


def localize_proper(zh, en, lang, pinyin_syllables):
    """專名／常見詞組在地化：拉丁語系回官方英文；其餘語言常見詞翻譯、專名音譯。

    zh: 原始中文詞組（僅在需要音譯時用）
    en: 官方英文值
    pinyin_syllables: zh 的拼音音節清單（lazy_pinyin(zh)）
    """
    if lang in LATIN:
        return en
    table = SUFFIX_TABLES.get(lang)
    if table is not None and en in table:
        return table[en]
    return transliterate_syllables(pinyin_syllables, lang)


def word_sep(lang):
    """ja 日文不空格；其餘語言以空白分隔。"""
    return "" if lang == "ja" else " "


